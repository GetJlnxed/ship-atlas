import {it,expect} from 'vitest';
import {mount} from '@vue/test-utils';
import fs from 'node:fs';
import ShipPvp from '../src/ShipPvp.vue';
const catalog=JSON.parse(fs.readFileSync('public/data/catalog.json','utf8'));
const ship=id=>catalog.ships.find(s=>s.id===id);
const props=id=>({ship:ship(id),data:catalog.pvp});
it('disables unverified pilot control while allowing crew assignment and showing weapon descriptions',async()=>{
 const w=mount(ShipPvp,{props:props('orig-600i-explorer')});
 expect(w.get('.pvp-stations summary').text()).toContain('активные орудия: 3');
 expect(w.get('.pvp-control-status').text()).toContain('Возможность управления пилотом неизвестна');
 expect(w.get('.pvp-link input').attributes('disabled')).toBeDefined();
 await w.findAll('.pvp-segments button')[1].trigger('click');
 expect(w.get('.pvp-stations summary').text()).toContain('активные орудия: 5');
 expect(w.get('.pvp-link input').attributes('disabled')).toBeDefined();
 expect(w.findAll('.pvp-armor-preview small').map(x=>x.text())).toEqual([
  'Баллистический гатлинг · S4','Баллистический гатлинг · S5','Баллистическая пушка · S4'
 ]);
 expect(w.findAll('.pvp-preview-threats')[1].text()).toContain('Быстрый тяжёлый атакующий');
 await w.findAll('.pvp-tabs button')[1].trigger('click');
 const ad=w.get('[data-weapon="AD5B Ballistic Gatling"] .pvp-weapon-threats');
 expect(ad.text()).toContain('Быстрый тяжёлый атакующий');
 expect(ad.text()).toContain('M80');
 expect(ad.text()).toContain('Групповой перехват');
 expect(ad.text()).not.toContain('Манёвренный дуэлянт');
 w.unmount();
});
it('Paladin wing capability is usable with a visible LIVE caveat; central turret stays unknown',async()=>{
 const w=mount(ShipPvp,{props:props('anvl-paladin')});
 const links=w.findAll('.pvp-link input');
 expect(links.map(x=>x.attributes('disabled')===undefined)).toEqual([true,false,true]);
 expect(w.get('.pvp-control-status').text()).toContain('Возможность известна');
 await links[0].setValue(true);await links[2].setValue(true);
 expect(w.get('.pvp-stations summary').text()).toContain('активные орудия: 4');
 expect(w.get('.pvp-control-caveat').text()).toContain('Их работа в текущем LIVE не проверена');
 expect(w.get('.pvp-control-caveat').element.closest('details')).toBeNull();
 await w.findAll('.pvp-segments button')[1].trigger('click');
 expect(w.get('.pvp-stations summary').text()).toContain('активные орудия: 8');
 expect(w.get('.pvp-stations summary').text()).toContain('занятые турели: 1');
 await links[0].setValue(false);await links[2].setValue(false);
 expect(w.find('.pvp-control-caveat').exists()).toBe(false);
 await w.setProps(props('orig-600i-explorer'));
 expect(w.findAll('.pvp-link input').every(x=>x.attributes('disabled')!==undefined)).toBe(true);
 w.unmount();
});
it('LIVE verification expires to known capability, and a current failure disables pilot control',async()=>{
 const base=props('anvl-paladin');
 const p=structuredClone(catalog.pvp.profiles[base.ship.id]);
 const liveCheck={status:'verified',patch:catalog.pvp.patch,source:'https://example.test/proof',checkedAt:'2026-10-23'};
 p.stations[0].pilotControl.liveCheck=liveCheck;
 const data={...catalog.pvp,profiles:{...catalog.pvp.profiles,[base.ship.id]:p}};
 const w=mount(ShipPvp,{props:{...base,data}});
 expect(w.get('.pvp-control-status').text()).toBe('Проверено в текущем LIVE');
 await w.get('.pvp-link input').setValue(true);
 expect(w.find('.pvp-control-caveat').exists()).toBe(false);
 await w.setProps({data:{...data,patch:'4.11.0-live.1'}});
 expect(w.get('.pvp-link input').attributes('disabled')).toBeUndefined();
 expect(w.get('.pvp-control-status').text()).toContain('в текущем LIVE не проверена');
 expect(w.find('.pvp-control-caveat').exists()).toBe(true);
 const broken=structuredClone(data);broken.profiles[base.ship.id].stations[0].pilotControl.liveCheck.status='unavailable';
 await w.setProps({data:broken});
 expect(w.get('.pvp-link input').attributes('disabled')).toBeDefined();
 expect(w.get('.pvp-control-status').text()).toBe('В текущем LIVE не работает');
 expect(w.get('.pvp-stations summary').text()).toContain('активные орудия: 0');
 w.unmount();
});
